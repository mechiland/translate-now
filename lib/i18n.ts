const dictionaries = { zh, en };

export function resolveUiLang(
  pref: UiLang,
  browserLang = typeof navigator !== 'undefined' ? navigator.language : 'en',
): 'zh' | 'en' {
  if (pref === 'zh' || pref === 'en') return pref;
  return browserLang.toLowerCase().startsWith('zh') ? 'zh' : 'en';
}

export type TFunction = (key: MessageKey, ...args: (string | number)[]) => string;

export function createT(pref: UiLang): TFunction {
  const dict = dictionaries[resolveUiLang(pref)];
  return (key, ...args) =>
    dict[key].replace(/\{(\d+)\}/g, (_, i: string) => String(args[Number(i)] ?? ''));
}

export function errorText(t: TFunction, kind: string): string {
  const map: Record<string, MessageKey> = {
    auth: 'errAuth',
    rate_limit: 'errRateLimit',
    network: 'errNetwork',
    timeout: 'errTimeout',
    not_found: 'errNotFound',
    config: 'errConfig',
    server: 'errServer',
    bad_request: 'errBadRequest',
    parse: 'errParse',
  };
  const key = map[kind];
  return key ? t(key) : kind;
}
